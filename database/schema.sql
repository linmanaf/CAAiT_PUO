CREATE TABLE IF NOT EXISTS admins (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 display_name VARCHAR(120) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 must_change BOOLEAN NOT NULL DEFAULT 1,
 session_version INT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS feedback (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 request_id CHAR(36) NOT NULL UNIQUE,
 name VARCHAR(120) NULL, email VARCHAR(254) NULL,
 module VARCHAR(40) NOT NULL, rating TINYINT UNSIGNED NOT NULL,
 message TEXT NOT NULL,
 status ENUM('new','read','resolved') NOT NULL DEFAULT 'new',
 is_test BOOLEAN NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX (created_at,is_test)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 event_id CHAR(36) NOT NULL UNIQUE,
 visitor_id CHAR(64) NOT NULL,
 module VARCHAR(40) NOT NULL,
 is_test BOOLEAN NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX (created_at,is_test), INDEX(visitor_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rate_limits (
 bucket CHAR(64) NOT NULL PRIMARY KEY,
 hits INT UNSIGNED NOT NULL DEFAULT 1,
 expires_at DATETIME NOT NULL
) ENGINE=InnoDB;
